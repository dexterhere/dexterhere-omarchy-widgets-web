// Renders the host rules (src/lib/hosts.ts RULES) into deploy/ configs for Caddy, nginx, Netlify
// and Vercel. Usage: PUBLIC_SITE_ORIGIN=https://example.com PUBLIC_DOCS_ORIGIN=https://docs.example.com \
//   bun run emit:host-config   (defaults to those two placeholder origins)
// Everything interpolated is validated first: origins by parseOrigin(), the start page by SAFE_PATH.
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { RULES, SECURITY_HEADERS, type HostCtx } from '../src/lib/hosts.ts';
import { parseOrigins } from '../src/lib/origins.ts';
import { docsHome, ROOT } from './host-env.ts';

const SAFE_PATH = /^\/[A-Za-z0-9._~/-]*$/;
const ROOT_DIR = '/srv/omarchy-widgets/build'; // where the build is copied on the server

/** What every generator needs, checked: origins are plain origins, the start page a plain path. */
export function ctxFor(env: Record<string, string | undefined>, home = docsHome()): HostCtx {
  const o = parseOrigins(env);
  const site = o.site || 'https://example.com';
  const docs = o.docs || 'https://docs.example.com';
  const ctx = parseOrigins({ PUBLIC_SITE_ORIGIN: site, PUBLIC_DOCS_ORIGIN: docs });
  const start = home.replace(/^\/docs/, '');
  if (!SAFE_PATH.test(start) || start.includes('..'))
    throw new Error(`unsafe docs start page: ${home}`);
  return { siteOrigin: ctx.site, docsOrigin: ctx.docs, docsHome: home };
}

const host = (origin: string) => new URL(origin).hostname; // no port: server_name and host matches never carry one
const start = (c: HostCtx) => c.docsHome.replace(/^\/docs/, '');
const GEN = 'GENERATED by `bun run emit:host-config` from src/lib/hosts.ts. Do not edit.';
const assetPaths = () => [
  ...RULES.docsPassthroughPrefixes.map((p) => `${p}*`),
  ...RULES.docsPassthroughDirs.map((p) => `${p}*`),
  ...RULES.docsPassthroughFiles
];

const PF_WASM = '^/pagefind/wasm\\..*\\.pagefind$';
const hdrLines = (indent: string, sep: string) =>
  Object.entries(SECURITY_HEADERS)
    .map(([k, v]) => `${indent}${k}${sep}${/[ ']/.test(v) ? `"${v}"` : v}`)
    .join('\n');

/** Port of the catch-all that answers 421 for unknown hosts (HTTPS origins use the port-80 listener). */
const catchAllPort = (c: HostCtx) => {
  const u = new URL(c.siteOrigin);
  return u.protocol === 'http:' ? u.port || '80' : '80';
};

export function caddyfile(c: HostCtx): string {
  const common = `	root * ${ROOT_DIR}
	encode zstd gzip
	header {
${hdrLines('\t\t', ' ')}
	}`;
  // Redirects sit in handle + route so they run first, in the written order: strip /docs from the request
  // first, then redirect to the fixed docs origin plus {uri}, the ESCAPED path and query as sent
  // (never the decoded path).
  return `# ${GEN}
# One build, two hostnames. Copy build/ to ${ROOT_DIR}.

${c.siteOrigin} {
${common}
	@oldDocs path /docs /docs/*
	handle @oldDocs {
		route {
			uri strip_prefix /docs
			redir ${c.docsOrigin}{uri} ${RULES.docsMovedStatus}
		}
	}
	handle {
		file_server
	}
	handle_errors {
		@badRequest expression {http.error.status_code} == 400
		handle @badRequest {
			rewrite * /400/index.html
			file_server
		}
		@serverError expression {http.error.status_code} >= 500
		handle @serverError {
			rewrite * /500/index.html
			file_server
		}
		rewrite * /404.html
		file_server
	}
}

${c.docsOrigin} {
${common}
	@home path /
	handle @home {
		route {
			uri replace / ${start(c)} 1
			redir ${c.docsOrigin}{uri} ${RULES.rootRedirectStatus}
		}
	}
	@oldDocs path /docs /docs/*
	handle @oldDocs {
		route {
			uri strip_prefix /docs
			redir ${c.docsOrigin}{uri} ${RULES.docsMovedStatus}
		}
	}
	@wasm path_regexp ${PF_WASM}
	header @wasm Content-Type application/wasm
	@pfbin path_regexp ^/pagefind/.*\\.pf_[a-z]+$
	header @pfbin Content-Type application/octet-stream
	@static path ${assetPaths().join(' ')}
	handle @static {
		file_server
	}
	handle {
		rewrite * ${RULES.docsPrefix}{path}
		file_server
	}
	handle_errors {
		@badRequest expression {http.error.status_code} == 400
		handle @badRequest {
			rewrite * /400/index.html
			file_server
		}
		@serverError expression {http.error.status_code} >= 500
		handle @serverError {
			rewrite * /500/index.html
			file_server
		}
		rewrite * /404.html
		file_server
	}
}

# Any other Host header: 421, nothing is served.
http://:${catchAllPort(c)} {
	respond "Unknown host" 421
}
`;
}

export function nginxConf(c: HostCtx): string {
  const docs = host(c.docsOrigin);
  const site = host(c.siteOrigin);
  const hdr = Object.entries(SECURITY_HEADERS)
    .map(([k, v]) => `	add_header ${k} "${v}" always;`)
    .join('\n');
  const statics = [
    ...RULES.docsPassthroughPrefixes.map((p) =>
      p === '/pagefind/'
        ? `	location ^~ ${p} {
		types { application/wasm pagefind; text/javascript js; text/css css; application/json json; }
		default_type application/octet-stream;
		try_files $uri =404;
	}`
        : `	location ^~ ${p} { try_files $uri =404; }`
    ),
    ...RULES.docsPassthroughDirs.map(
      (p) => `	location ^~ ${p} { try_files $uri $uri/index.html =404; }`
    ),
    ...RULES.docsPassthroughFiles.map((f) => `	location = ${f} { try_files $uri =404; }`)
  ].join('\n');
  return `# ${GEN}
# Include inside http { }. Serve TLS however you like (certbot, a proxy in front...).
# Redirect targets are built from the fixed origins and the RAW request URI ($request_uri), never
# from the Host header or the decoded $uri.

map $request_uri $ow_old_docs {
	default "";
	"~^/docs(?<rest>(?:[/?].*)?)$" "r$rest";
}
map $request_uri $ow_slashless {
	default "";
	"~^(?<p>(?:/[^/?]+)*/[^/.?]+)(?<q>\\?.*)?$" "$p/$q";
}

# Any other Host header: 421, nothing is served.
server {
	listen 80 default_server;
	server_name _;
	return 421;
}

server {
	listen 80;
	server_name ${site};
	root ${ROOT_DIR};
	error_page 400 /400/index.html;
	error_page 404 /404.html;
	error_page 500 502 503 504 /500/index.html;
${hdr}
	if ($ow_old_docs ~ ^r(.*)$) { return ${RULES.docsMovedStatus} ${c.docsOrigin}$1; }
	if ($ow_slashless) { return 301 ${c.siteOrigin}$ow_slashless; }
	location / { try_files $uri $uri/index.html =404; }
}

server {
	listen 80;
	server_name ${docs};
	root ${ROOT_DIR};
	error_page 400 /400/index.html;
	error_page 404 /404.html;
	error_page 500 502 503 504 /500/index.html;
${hdr}
	if ($ow_old_docs ~ ^r(.*)$) { return ${RULES.docsMovedStatus} ${c.docsOrigin}$1; }
	if ($ow_slashless) { return 301 ${c.docsOrigin}$ow_slashless; }
	location = / { return ${RULES.rootRedirectStatus} ${c.docsOrigin}${start(c)}$is_args$args; }
${statics}
	location / {
		rewrite ^ ${RULES.docsPrefix}$uri break;
		try_files $uri $uri/index.html =404;
	}
}
`;
}

export function netlifyHeaders(): string {
  const h = Object.entries(SECURITY_HEADERS)
    .map(([k, v]) => `  ${k}: ${v}`)
    .join('\n');
  return `# ${GEN}
/*
${h}
/pagefind/wasm.*
  Content-Type: application/wasm
/pagefind/index/*
  Content-Type: application/octet-stream
/pagefind/fragment/*
  Content-Type: application/octet-stream
/pagefind/filter/*
  Content-Type: application/octet-stream
`;
}

export function netlifyRedirects(c: HostCtx): string {
  const docs = new URL(c.docsOrigin);
  const site = new URL(c.siteOrigin);
  const lines: string[] = [`# ${GEN}`];
  // Netlify matches rules top to bottom. Rules with a host match that host only.
  for (const scheme of ['http', 'https']) {
    const d = `${scheme}://${docs.hostname}`;
    const s = `${scheme}://${site.hostname}`;
    lines.push('');
    for (const p of [...RULES.docsPassthroughPrefixes, ...RULES.docsPassthroughDirs])
      lines.push(`${d}${p}* ${p}:splat 200`);
    for (const f of RULES.docsPassthroughFiles) lines.push(`${d}${f} ${f} 200`);
    lines.push(`${d}/docs ${c.docsOrigin}/ ${RULES.docsMovedStatus}!`);
    lines.push(`${d}/docs/* ${c.docsOrigin}/:splat ${RULES.docsMovedStatus}!`);
    lines.push(`${d}/ ${c.docsOrigin}${start(c)} ${RULES.rootRedirectStatus}!`);
    lines.push(`${d}/* ${RULES.docsPrefix}/:splat 200!`);
    lines.push(`${s}/docs ${c.docsOrigin}/ ${RULES.docsMovedStatus}!`);
    lines.push(`${s}/docs/* ${c.docsOrigin}/:splat ${RULES.docsMovedStatus}!`);
  }
  return lines.join('\n') + '\n';
}

function vercelHeaders() {
  return [
    {
      source: '/(.*)',
      headers: Object.entries(SECURITY_HEADERS).map(([key, value]) => ({ key, value }))
    },
    {
      source: '/pagefind/:file(wasm\\..+\\.pagefind)',
      headers: [{ key: 'Content-Type', value: 'application/wasm' }]
    },
    {
      source: '/pagefind/:dir(index|fragment|filter)/:rest*',
      headers: [{ key: 'Content-Type', value: 'application/octet-stream' }]
    }
  ];
}

/**
 * Project file for a Vercel deployment on ONE hostname (docs under /docs/). It goes at the repo
 * root. The two-hostname rules in deploy/vercel.json need both origins and a domain you own.
 */
export function vercelProjectJson(): string {
  const config = {
    $schema: 'https://openapi.vercel.sh/vercel.json',
    framework: null,
    installCommand: 'bun install --frozen-lockfile',
    // Strict first: if GitHub is unreachable or rate limited, the build fails and Vercel keeps serving
    // the previous production deployment instead of publishing an empty widget list.
    buildCommand: 'bun run registry -- --strict && bun run build',
    outputDirectory: 'build',
    trailingSlash: true,
    headers: vercelHeaders(),
    // The v0.1 draft snapshot was replaced by the stable v0.1 docs; keep old links and search hits alive.
    redirects: [
      { source: '/docs/v0.1-draft/:path*', destination: '/docs/v0.1/:path*', permanent: true }
    ]
  };
  return JSON.stringify(config, null, 2) + '\n';
}

export function vercelJson(c: HostCtx): string {
  // has.value is a regular expression: anchor it and escape the dots
  const rx = (o: string) => `^${host(o).replace(/\./g, '\\.')}$`;
  const dHost = [{ type: 'host', value: rx(c.docsOrigin) }];
  const sHost = [{ type: 'host', value: rx(c.siteOrigin) }];
  const config = {
    $schema: 'https://openapi.vercel.sh/vercel.json',
    trailingSlash: true,
    headers: vercelHeaders(),
    redirects: [
      {
        source: '/docs/:path*',
        has: dHost,
        destination: `${c.docsOrigin}/:path*`,
        statusCode: RULES.docsMovedStatus
      },
      {
        source: '/',
        has: dHost,
        destination: `${c.docsOrigin}${start(c)}`,
        statusCode: RULES.rootRedirectStatus
      },
      {
        source: '/docs/:path*',
        has: sHost,
        destination: `${c.docsOrigin}/:path*`,
        statusCode: RULES.docsMovedStatus
      }
    ],
    rewrites: [
      ...assetPaths().map((p) => ({
        source: p.endsWith('*') ? `${p.slice(0, -1)}:path*` : p,
        has: dHost,
        destination: p.endsWith('*') ? `${p.slice(0, -1)}:path*` : p
      })),
      { source: '/:path*', has: dHost, destination: `${RULES.docsPrefix}/:path*` }
    ]
  };
  return JSON.stringify(config, null, 2) + '\n';
}

export const OUTPUTS = (c: HostCtx): Record<string, string> => ({
  Caddyfile: caddyfile(c),
  'nginx.conf': nginxConf(c),
  'netlify/_redirects': netlifyRedirects(c),
  'netlify/_headers': netlifyHeaders(),
  'vercel.json': vercelJson(c)
});

if (import.meta.main) {
  const c = ctxFor(process.env);
  for (const [name, text] of Object.entries(OUTPUTS(c))) {
    const file = join(ROOT, 'deploy', name);
    mkdirSync(join(file, '..'), { recursive: true });
    writeFileSync(file, text);
    console.log(`wrote deploy/${name}`);
  }
  writeFileSync(join(ROOT, 'vercel.json'), vercelProjectJson());
  console.log('wrote vercel.json (one hostname)');
  console.log(`site ${c.siteOrigin}  docs ${c.docsOrigin}  start ${start(c)}`);
}
