// Generates src/lib/make/validators.generated.js: the registry's JSON Schema validators (listing,
// widget.json, manifest.json) compiled ahead of time by Ajv, so the /make/ check panel runs the SAME
// schemas in the browser without `new Function` (the site's CSP forbids unsafe-eval).
// Usage: bun scripts/gen-make-validators.ts [--check]   (--check fails if the file is stale)
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { format } from 'prettier';
import { MANIFEST_SCHEMA } from './build-registry';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const OUT = join(ROOT, 'src/lib/make/validators.generated.js');
const read = (n: string) => JSON.parse(readFileSync(join(ROOT, 'registry/schema', n), 'utf8'));

export async function generate(): Promise<string> {
  const ajv = new Ajv2020({
    allErrors: true,
    strict: true,
    allowUnionTypes: true,
    code: { source: true, esm: true }
  });
  ajv.addSchema(read('listing.schema.json'), 'listing');
  ajv.addSchema(read('widget.schema.json'), 'widget');
  ajv.addSchema(MANIFEST_SCHEMA, 'manifest');
  const code = standaloneCode(ajv, {
    listing: 'listing',
    widget: 'widget',
    manifest: 'manifest'
  });
  // Ajv's ESM output still pulls its two runtime helpers with require(); turn them into imports.
  const imports: string[] = [];
  const body = code.replace(
    /const (\w+) = require\(("[^"]+")\)\.default;/g,
    (_m, name: string, mod: string) => (imports.push(`import ${name} from ${mod};`), '')
  );
  const src = `/* eslint-disable */\n// @ts-nocheck\n// GENERATED by scripts/gen-make-validators.ts from registry/schema/*. Do not edit.\n${imports.join('\n')}\n${body}`;
  return format(src, {
    parser: 'babel',
    singleQuote: true,
    printWidth: 100,
    trailingComma: 'none'
  });
}

if (import.meta.main) {
  const out = await generate();
  if (process.argv.includes('--check')) {
    if (!existsSync(OUT) || readFileSync(OUT, 'utf8') !== out) {
      console.error(
        'src/lib/make/validators.generated.js is stale: run bun scripts/gen-make-validators.ts'
      );
      process.exit(1);
    }
  } else writeFileSync(OUT, out);
}
