import { contrast, luminance, mix, shiftLightness } from './color';
import { DEFAULT_DARK, DEFAULT_LIGHT, STORAGE_KEY, THEMES, THEME_IDS } from './themes';
import { TOKEN_NAMES, type ThemeDef, type TokenName } from './types';

export interface ResolvedTheme {
  id: string;
  name: string;
  scheme: ThemeDef['scheme'];
  tokens: Record<TokenName, string>;
  /** One note per token the contrast rules forced us to move. */
  adjusted: string[];
}

/** The contrast floors every theme must meet (PLAN.md section 8). */
export const RULES = { text: 7, muted: 4.5, brandInk: 4.5, brand: 3, edge: 2 } as const;

/**
 * Nudge `fg` away from the page background in 0.5% lightness steps until it clears `min`
 * against every background in `bgs` (and `extra`, if given). The direction always helps, so
 * this is the smallest lightness shift that works.
 */
function pushAway(
  fg: string,
  bgs: string[],
  min: number,
  also: (v: string) => boolean = () => true
): string {
  const dir = luminance(bgs[0]) < 0.5 ? 1 : -1;
  let value = fg;
  while (bgs.some((b) => contrast(value, b) < min) || !also(value)) {
    const next = shiftLightness(value, dir * 0.005);
    if (next === value) throw new Error(`cannot reach ${min}:1 for ${fg}`);
    value = next;
  }
  return value;
}

export function resolveTheme(t: ThemeDef): ResolvedTheme {
  const adjusted: string[] = [];
  const fix = (name: string, fg: string, value: string, why: string) => {
    if (value !== fg) adjusted.push(`${name} ${fg} -> ${value} (${why})`);
    return value;
  };
  const text = fix(
    '--text',
    t.text,
    pushAway(t.text, [t.bg, t.surface], RULES.text),
    'text on bg and surface >= 7:1'
  );
  const text2 = fix(
    '--text-2',
    t.text2,
    pushAway(t.text2, [t.bg], RULES.muted),
    'text-2 on bg >= 4.5:1'
  );
  const muted = fix(
    '--muted',
    t.muted,
    pushAway(t.muted, [t.bg, t.surface], RULES.muted),
    'muted on bg and surface >= 4.5:1'
  );
  // Widget outlines must stand off the page and the deepest background (the wallpaper's colours).
  const borderStrong = fix(
    '--border-strong',
    t.borderStrong,
    pushAway(t.borderStrong, [t.bg, t.bgDeep], RULES.edge),
    'border-strong on bg and bg-deep >= 2:1'
  );
  // Brand moves away from the page background until it has 3:1 on it and brand-ink reads on it.
  const brand = fix(
    '--brand',
    t.brand,
    pushAway(t.brand, [t.bg], RULES.brand, (v) => contrast(t.brandInk, v) >= RULES.brandInk),
    'brand on bg >= 3:1, brand-ink on brand >= 4.5:1'
  );
  return {
    id: t.id,
    name: t.name,
    scheme: t.scheme,
    adjusted,
    tokens: {
      '--bg-deep': t.bgDeep,
      '--bg': t.bg,
      '--surface': t.surface,
      '--surface-2': t.surface2,
      // Derived, not an adjustment: official hairlines are often invisible on the page background.
      '--border': mix(t.bg, borderStrong, 0.45),
      '--border-strong': borderStrong,
      '--text': text,
      '--text-2': text2,
      '--muted': muted,
      '--brand': brand,
      '--brand-ink': t.brandInk,
      '--brand-soft': mix(t.bg, brand, 0.14),
      '--selection': mix(t.bg, brand, 0.32)
    }
  };
}

export const RESOLVED: readonly ResolvedTheme[] = THEMES.map(resolveTheme);

const HEADER =
  '/* GENERATED by scripts/gen-themes.ts from src/lib/themes/themes.ts. Do not edit. */';

export function themesCss(): string {
  const blocks = RESOLVED.map((r) => {
    const sel = r.id === DEFAULT_DARK ? `:root,\n[data-theme='${r.id}']` : `[data-theme='${r.id}']`;
    const body = TOKEN_NAMES.map((n) => `  ${n}: ${r.tokens[n]};`).join('\n');
    return `${sel} {\n  color-scheme: ${r.scheme};\n${body}\n}`;
  });
  return `${HEADER}\n${blocks.join('\n\n')}\n`;
}

/** id -> [bg, surface, text, brand] for the tab icon; generated here so it cannot drift. */
export function paletteJson(): string {
  return JSON.stringify(
    Object.fromEntries(
      RESOLVED.map((r) => [
        r.id,
        [r.tokens['--bg'], r.tokens['--surface'], r.tokens['--text'], r.tokens['--brand']]
      ])
    )
  );
}

export function bootScript(): string {
  return `${HEADER}
(function () {
  try {
    var ids = ${JSON.stringify(THEME_IDS)};
    var t = null;
    // ?theme=<id> comes from a link on the other host (localStorage is per origin): take it only
    // if it is a known id, remember it, and remove just that parameter from the address.
    var parts = location.search.slice(1).split('&');
    var rest = parts.filter(function (p) {
      return p.split('=')[0] !== 'theme';
    });
    if (rest.length !== parts.length && location.search) {
      var q = parts.filter(function (p) {
        return p.split('=')[0] === 'theme';
      })[0].split('=')[1];
      if (ids.indexOf(q) >= 0) {
        t = q;
        try {
          localStorage.setItem('${STORAGE_KEY}', t);
        } catch (e) {}
      }
      try {
        history.replaceState(
          history.state,
          '',
          location.pathname + (rest.length ? '?' + rest.join('&') : '') + location.hash
        );
      } catch (e) {}
    }
    if (t === null) {
      try {
        t = localStorage.getItem('${STORAGE_KEY}');
      } catch (e) {}
    }
    if (ids.indexOf(t) < 0) {
      t = matchMedia('(prefers-color-scheme: light)').matches ? '${DEFAULT_LIGHT}' : '${DEFAULT_DARK}';
    }
    document.documentElement.setAttribute('data-theme', t);
    // The first-visit tip is pending until it is dismissed: reserve its row from the first frame.
    try {
      if (localStorage.getItem('ow-theme-hint') !== '1')
        document.documentElement.setAttribute('data-hint', '1');
    } catch (e) {
      document.documentElement.setAttribute('data-hint', '1');
    }
  } catch (e) {}
  try {
    var pal = ${paletteJson()};
    // Tab icon and mobile browser chrome follow the theme (the same builder as src/lib/themes/favicon.ts).
    window.__owIcon = function (id) {
      var c = pal[id];
      if (!c) return;
      var at = [[0, 0], [6, 0], [0, 6], [6, 6]];
      var svg = "<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 11 11'>";
      for (var i = 0; i < 4; i++) {
        svg += "<rect x='" + at[i][0] + "' y='" + at[i][1] + "' width='5' height='5' fill='" + c[i] + "' stroke='" + c[2] + "' stroke-opacity='.35' stroke-width='.5'/>";
      }
      svg += '</svg>';
      var old = document.querySelector('link[rel="icon"]');
      var link = document.createElement('link');
      link.rel = 'icon';
      link.type = 'image/svg+xml';
      link.href = 'data:image/svg+xml,' + encodeURIComponent(svg);
      if (old) old.replaceWith(link);
      else document.head.appendChild(link);
      var m = document.querySelector('meta[name="theme-color"]');
      if (m) m.setAttribute('content', c[0]);
    };
    window.__owIcon(document.documentElement.getAttribute('data-theme'));
  } catch (e) {}
})();
`;
}
